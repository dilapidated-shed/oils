#!/usr/bin/env python2
"""Option_gen.py."""
from __future__ import print_function

import sys

from frontend import option_def


def _PrintD():
    """Generate D metadata from the same option declarations as the reference."""
    def string(s):
        return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')

    def boolean(b):
        return 'true' if b else 'false'

    print('// Generated by frontend/option_gen.py d; edit frontend/option_def.py.')
    print('module yshd.option_data;')
    print('''
struct OptionSpec {
    size_t number;
    string name;
    string shortFlag;
    string builtin;
    bool defaultValue;
    bool implemented;
    bool isParse;
    string[] groups;
}

immutable OptionSpec[] optionSpecs = [''')
    for opt in option_def.All():
        print('    OptionSpec(%d, %s, %s, %s, %s, %s, %s, [%s]),' % (
            opt.index, string(opt.name), string(opt.short_flag or ''),
            string(opt.builtin or ''), boolean(opt.default),
            boolean(opt.implemented), boolean(opt.is_parse),
            ', '.join(string(g) for g in opt.groups)))
    print('];')


def _CreateSum(sum_name, variant_names):
    """Similar to frontend/id_kind_gen.py Usage of SYNTHETIC ASDL module:

    C++:

    using option_asdl::opt_num
    opt_num::nounset

    Python:
    from _devbuild.gen.option_asdl import opt_num
    opt_num.nounset
    """
    from asdl import ast

    sum_ = ast.SimpleSum(
        [ast.MakeSimpleVariant(name) for name in variant_names],
        generate=['integers'])
    typ = ast.TypeDecl(sum_name, sum_)
    return typ


def main(argv):
    try:
        action = argv[1]
    except IndexError:
        raise RuntimeError('Action required')

    if action == 'd':
        _PrintD()
        return

    from asdl import ast
    from frontend import builtin_def

    # generate builtin::echo, etc.
    # This relies on the assigned option numbers matching ASDL's numbering!
    # TODO: Allow controlling the integer values in ASDL enums?

    option = _CreateSum('option', [opt.name for opt in option_def.All()])
    builtin = _CreateSum('builtin', [b.enum_name for b in builtin_def.All()])
    # TODO: could shrink array later.
    # [opt.name for opt in option_def.All() if opt.implemented])

    schema_ast = ast.Module('option', [], [], [option, builtin])

    if action == 'cpp':
        from asdl import gen_cpp

        out_prefix = argv[2]

        with open(out_prefix + '.h', 'w') as f:
            f.write("""\
#ifndef OPTION_ASDL_H
#define OPTION_ASDL_H

namespace option_asdl {

#define ASDL_NAMES struct
""")

            # Don't need option_str()
            v = gen_cpp.ClassDefVisitor(f, pretty_print_methods=False)
            v.VisitModule(schema_ast)

            f.write("""
}  // namespace option_asdl

#endif  // OPTION_ASDL_H
""")

    elif action == 'mypy':
        from asdl import gen_python

        # option_i type
        v = gen_python.GenMyPyVisitor(sys.stdout)
        v.VisitModule(schema_ast)

    else:
        raise RuntimeError('Invalid action %r' % action)


if __name__ == '__main__':
    try:
        main(sys.argv)
    except RuntimeError as e:
        print('FATAL: %s' % e, file=sys.stderr)
        sys.exit(1)
